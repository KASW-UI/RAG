-- 对应 Go 版 service/comment/rpc/internal/model/data_model.go:5-20 的 Subject
--
-- Go 侧由 model/db.go:15 的 db.AutoMigrate(&Subject{}, …) 建出；本项目 Java 侧改用 Flyway
-- （AGENTS.md §4.1「迁移机制已于 2026-10-21 改为幂等重放 / Flyway 条目处置完毕」的同款取舍）。
--
-- ⚠️ 时间列类型：Go 的 `time.Time` 在 gorm.io/driver/postgres 下建成 **TIMESTAMPTZ**，
--    不是 TIMESTAMP。AGENTS.md §0 item 2 已记录 users 域把两列 TIMESTAMP⇒TIMESTAMPTZ 的修复，
--    本域沿用该结论。理由不止「对齐」：get_comment_logic.go:139 要把 created_at
--    按本地时区格式化成 "2006-01-02 15:04:05"，而 Go 的 DSN（comment.yaml:9）显式带
--    TimeZone=Asia/Shanghai —— TIMESTAMPTZ 才能把这个时区语义搬到 wire 上。
--
-- ⚠️ id 是 autoIncrement，但**没有任何 Go 代码写它**：InsertCommentTx 走
--    ON CONFLICT upsert（comment.go:115-118），FindOneSubjectByTarget 按 (target_type,target_id) 查。
--    列仍然保留，与 GORM 模型逐列一致。

CREATE TABLE IF NOT EXISTS subject (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- Go: Id int64 `primaryKey;autoIncrement`
    target_type  VARCHAR(32)  NOT NULL,   -- Go: TargetType string `type:varchar(32);not null`
    target_id    VARCHAR(64)  NOT NULL,   -- Go: TargetId   string `type:varchar(64);not null`
    total_count  BIGINT       NOT NULL DEFAULT 0,   -- Go: TotalCount int64 `not null;default:0` 总评论数
    root_count   BIGINT       NOT NULL DEFAULT 0,   -- Go: RootCount  int64 `not null;default:0` 根评论数
    state        INTEGER      NOT NULL DEFAULT 0,   -- Go: State int32 `not null;default:0` 0正常 1关闭 2仅粉丝
    attribute    BIGINT       NOT NULL DEFAULT 0,   -- Go: Attribute int64 `not null;default:0` 属性位图
    owner_id     BIGINT       NOT NULL,              -- Go: OwnerId   int64 `not null` 作者ID（评论区主）
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,   -- Go: CreatedAt time.Time `autoCreateTime`
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP    -- Go: UpdatedAt time.Time `autoUpdateTime`
);

-- Go: `uniqueIndex:idx_target`（TargetType 与 TargetId 两列都带 tag ⇒ 复合唯一索引）
-- 语义作用：它就是 InsertCommentTx 的 ON CONFLICT 冲突目标（comment.go:116）
--          ——「同一 target 只允许一行 subject」靠它仲裁。
-- ⚠️ 这同时也是 update_subject_state / delete_comment 的越权判据来源
--    （subject.OwnerId，见 update_subject_state_logic.go:85）。
CREATE UNIQUE INDEX IF NOT EXISTS idx_target
    ON subject (target_type, target_id);